// Which field labels follow the institute type (Course → Class, Session → Academic Year).
function fieldLabel(f, words) {
  if (f.word === 'program') return words.program;
  if (f.word === 'course') return words.course;
  if (f.word === 'year') return words.year;
  if (f.word === 'batch') return words.batch;
  return f.label;
}

