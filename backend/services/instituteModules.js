// ============================================================================
// iCRM Institute — the institute's own modules, in one place.
// ============================================================================
// Each module here has a real table (made in db-phase60-institute.js), a row in
// the `modules` registry and its fields in `module_fields`, so it gets the same
// list, filters, export, import, forms and record page as every other module.
// routes/instituteRecords.js serves them all with one router.
//
//   table      the table
//   branch     'own'    every record belongs to one branch (required)
//              'shared' branch_id empty = used by all branches; set = one branch only
//              'self'   the branches table itself
//   labels     the menu words for each institute type (Settings → Institute)
//   fields     the fields, in form order. type = the field type of module_fields.
//              only: 'coaching' | 'school' | 'college' — shown for that type only
//   unique     columns that must not repeat (a friendly message instead of an error)
//   search     the columns the list search box looks in
//   order      the list's default order
// ============================================================================

